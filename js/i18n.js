  function t(lang, key, vars) {
    const dict = UI_STRINGS[lang] || UI_STRINGS.en;
    let template = dict[key] !== undefined ? dict[key] : UI_STRINGS.en[key] || key;
    if (vars) {
      Object.keys(vars).forEach((k) => {
        template = template.split('{' + k + '}').join(String(vars[k]));
      });
    }
    return template;
  }

  async function loadLocalePack(lang) {
    if (!lang || lang === 'en' || !SUPPORTED_SET.has(lang)) {
      return null;
    }
    if (localeCache.has(lang)) {
      return localeCache.get(lang);
    }
    try {
      const resp = await fetch('locales/' + lang + '.json');
      if (!resp.ok) throw new Error('HTTP ' + resp.status);
      const json = await resp.json();
      localeCache.set(lang, json);
      return json;
    } catch (_err) {
      return null;
    }
  }

  function buildLocalizedData(baseData, pack) {
    if (!pack) return baseData;

    const arenas = baseData.arenas.map((a) => ({
      ...a,
      name: (pack.arenas && pack.arenas[a.id]) || a.name
    }));

    const hairForms = baseData.hairForms.map((hf) => {
      const tr = pack.hairForms && pack.hairForms[hf.id];
      if (!tr) return hf;
      return {
        ...hf,
        name: tr.name || hf.name,
        shortLabel: tr.shortLabel || hf.shortLabel,
        characterName: tr.characterName || hf.characterName,
        era: tr.era || hf.era,
        multiplier: tr.multiplier || hf.multiplier,
        powerExample: tr.powerExample || hf.powerExample,
        whoUsesIt: tr.whoUsesIt || hf.whoUsesIt,
        howUnlocked: tr.howUnlocked || hf.howUnlocked,
        meaningForKids: tr.meaningForKids || hf.meaningForKids,
        funFact: tr.funFact || hf.funFact
      };
    });

    const timelineSagas = baseData.timelineSagas.map((s) => {
      const tr = pack.timelineSagas && pack.timelineSagas[s.id];
      if (!tr) return s;
      return {
        ...s,
        eraFullName: tr.eraFullName || s.eraFullName,
        years: tr.years || s.years,
        title: tr.title || s.title,
        mainHero: tr.mainHero || s.mainHero,
        mainEnemy: tr.mainEnemy || s.mainEnemy,
        keyEvents: tr.keyEvents || s.keyEvents,
        hairOrFormUnlocked: tr.hairOrFormUnlocked || s.hairOrFormUnlocked,
        kidLesson: tr.kidLesson || s.kidLesson
      };
    });

    const fighters = baseData.fighters.map((f) => {
      const tr = pack.fighters && pack.fighters[f.id];
      if (!tr) return f;
      const localizedForms = (f.forms || []).map((sf, idx) => {
        const trForm = tr.forms && tr.forms[idx];
        return trForm
          ? {
              ...sf,
              label: trForm.label || sf.label,
              power: trForm.power || sf.power
            }
          : sf;
      });
      return {
        ...f,
        name: tr.name || f.name,
        series: tr.series || f.series,
        race: tr.race || f.race,
        signatureMove: tr.signatureMove || f.signatureMove,
        peakPowerLabel: tr.peakPowerLabel || f.peakPowerLabel,
        kidBio: tr.kidBio || f.kidBio,
        forms: localizedForms
      };
    });

    const fusionRecipes = baseData.fusionRecipes.map((r) => {
      const tr = pack.fusionRecipes && pack.fusionRecipes[r.id];
      if (!tr) return r;
      return {
        ...r,
        methodName: tr.methodName || r.methodName,
        resultName: tr.resultName || r.resultName,
        power: tr.power || r.power,
        story: tr.story || r.story
      };
    });

    const quizQuestions = baseData.quizQuestions.map((q, idx) => {
      const tr = pack.quizQuestions && pack.quizQuestions[idx];
      if (!tr || !Array.isArray(tr.options) || tr.options.length !== q.options.length) {
        return q;
      }
      return {
        ...q,
        question: tr.question || q.question,
        options: tr.options,
        explanation: tr.explanation || q.explanation
      };
    });

    return {
      arenas,
      hairForms,
      timelineSagas,
      fighters,
      fusionRecipes,
      quizQuestions
    };
  }

